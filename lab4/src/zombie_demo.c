/*
 * zombie_demo.c — демонстрация зомби-процессов
 *
 * Зомби-процесс — это процесс, который уже завершился (вызвал exit),
 * но родитель ещё не забрал его код возврата через wait()/waitpid().
 * Ядро хранит запись о нём в таблице процессов в состоянии Z (zombie/defunct).
 */
#include <stdio.h>
#include <stdlib.h>
#include <unistd.h>
#include <sys/wait.h>
#include <sys/types.h>

int main(void) {
    /* Создаём дочерний процесс */
    pid_t pid = fork();

    if (pid < 0) {                 /* fork не удался */
        perror("fork");
        return 1;
    }

    if (pid == 0) {
        /*ВЕТКА РЕБЁНКА*/
        printf("[ребёнок ] pid=%d, ppid=%d — завершаюсь\n",
               getpid(), getppid());
        fflush(stdout);

        /*
         * Ребёнок вызывает exit() — ядро освобождает его память,
         * дескрипторы и т.д., НО оставляет запись в таблице процессов,
         * потому что код возврата ещё не забран родителем.
         * С этого момента процесс находится в состоянии Z (зомби).
         */
        exit(0);
    }

    /*ВЕТКА РОДИТЕЛЯ*/
    printf("[родитель] pid=%d, породил ребёнка pid=%d\n",
           getpid(), pid);
    printf("[родитель] сплю 20 секунд и НЕ вызываю wait()\n");
    printf("[родитель] в это время ребёнок — ЗОМБИ\n\n");
    printf("[родитель] открой другой терминал и посмотри:\n");
    printf("            ps -o pid,ppid,stat,comm -p %d\n", pid);
    printf("            ps -eo pid,ppid,stat,comm | grep ' Z '\n\n");
    fflush(stdout);

    /*
     * Спим 20 секунд — это «окно», в течение которого ребёнок
     * висит зомби: он уже мёртв, но ещё не «оплакан» родителем.
     * В это время в ps его STAT = Z.
     */
    sleep(20);

    /*РЕАПИМ ЗОМБИ*/
    int status;

    /*
     * waitpid() забирает код возврата ребёнка и удаляет его запись
     * из таблицы процессов. После этого зомби исчезает,
     * а PID освобождается для повторного использования.
     */
    printf("[родитель] вызываю waitpid(%d, ...) — реаплю зомби\n", pid);
    pid_t r = waitpid(pid, &status, 0);
    printf("[родитель] waitpid вернул %d, status=0x%x — зомби исчез\n",
           (int)r, status);

    /* Даём время посмотреть, что зомби больше нет */
    printf("[родитель] сплю 10 секунд — теперь процессов в состоянии Z нет\n");
    fflush(stdout);
    sleep(10);

    return 0;
}